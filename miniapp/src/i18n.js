export function translate(lang, path, params) {
  const parts = path.split('.');
  let value = i18n[lang] ?? i18n.ru;
  for (const part of parts) value = value?.[part];
  if (value == null) value = parts.reduce((acc, part) => acc?.[part], i18n.ru);
  if (typeof value !== 'string' || !params) return value;
  return value.replace(/\{(\w+)\}/g, (match, name) => (params[name] == null ? match : String(params[name])));
}
